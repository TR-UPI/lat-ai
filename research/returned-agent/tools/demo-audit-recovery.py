def cli(label,tool,args,expected=0):
    command=[sys.executable,str(ROOT/'tools'/tool),*map(str,args)]
    run=subprocess.run(command,capture_output=True,text=True,encoding='utf-8',timeout=40,creationflags=getattr(subprocess,'CREATE_NO_WINDOW',0))
    r.lease.publish(demo/(label+'.log'),(run.stdout+run.stderr).encode())
    commands.append({'label':label,'tool':tool,'returncode':run.returncode,'expected':expected})
    if run.returncode!=expected:raise AssertionError((label,run.returncode,run.stderr))
    return json.loads(run.stdout) if run.stdout.strip().startswith('{') else None
